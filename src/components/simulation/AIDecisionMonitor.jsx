
import { useSimulation } from '../../state/SimulationContext'
import './AIDecisionMonitor.css'

const formatScore = (value) =>
  typeof value === 'number' ? value.toFixed(2) : '—'

export default function AIDecisionMonitor() {
  const { isRunning, aiResults } = useSimulation()

  const relevance = aiResults?.relevance
  const risk = aiResults?.risk
  const suppression = aiResults?.suppression
  const selectedFeedback = aiResults?.feedback ?? 'none'
  const fusedData = aiResults?.fusedData

  const hasResults = Boolean(aiResults)

  return (
    <section className="aditi-ai-panel">
      <div className="aditi-ai-heading">
        <div>
          <span>06 / INTELLIGENCE PIPELINE</span>
          <h2>ADITI AI Decision Monitor</h2>
        </div>

        <span className="aditi-ai-status">
          {hasResults ? '● PROCESSING' : '○ STANDBY'}
        </span>
      </div>

      {hasResults ? (
        <>
          <div className="aditi-ai-grid">
            <article className="aditi-ai-card">
              <span className="aditi-ai-label">
                RELEVANCE ANALYSIS
              </span>
              <strong className="aditi-ai-cyan">
                {formatScore(relevance?.score)}
              </strong>
              <small>
                Level: {relevance?.level ?? 'unknown'}
              </small>
            </article>

            <article className="aditi-ai-card">
              <span className="aditi-ai-label">
                RISK ASSESSMENT
              </span>
              <strong className="aditi-ai-warning">
                {(risk?.level ?? 'unknown').toUpperCase()}
              </strong>
              <small>
                Score: {formatScore(risk?.score)}
              </small>
            </article>

            <article className="aditi-ai-card">
              <span className="aditi-ai-label">
                SUPPRESSION DECISION
              </span>
              <strong className="aditi-ai-success">
                {(suppression?.action ?? 'unknown').toUpperCase()}
              </strong>
              <small>
                {suppression?.reason ?? 'No decision'}
              </small>
            </article>

            <article className="aditi-ai-card">
              <span className="aditi-ai-label">
                FEEDBACK OUTPUT
              </span>
              <strong className="aditi-ai-magenta">
                {selectedFeedback.toUpperCase()}
              </strong>
              <small>Selected by processing engine</small>
            </article>
          </div>

          <div className="aditi-ai-fusion">
            <div className="aditi-ai-fusion-head">
              <h3>Fused Sensor Context</h3>
              <span>
                {fusedData?.activeSources?.length ?? 0} SOURCES
              </span>
            </div>

            <div className="aditi-ai-fusion-grid">
              <div>
                <span>DETECTED OBJECT</span>
                <strong>
                  {fusedData?.detectedObject ?? 'None'}
                </strong>
              </div>

              <div>
                <span>NEAREST DISTANCE</span>
                <strong>
                  {typeof fusedData?.nearestDistance === 'number'
                    ? `${fusedData.nearestDistance.toFixed(2)} m`
                    : '—'}
                </strong>
              </div>

              <div>
                <span>MOVEMENT</span>
                <strong>
                  {fusedData?.movement ?? 'Unknown'}
                </strong>
              </div>

              <div>
                <span>DETECTED SOUND</span>
                <strong>
                  {fusedData?.detectedSound ?? 'None'}
                </strong>
              </div>
            </div>
          </div>

          <p className="aditi-ai-note">
            Decision generated at:{' '}
            {new Date(aiResults.timestamp).toLocaleTimeString()}.
            All values are generated by a conceptual,
            rule-based software simulation.
          </p>
        </>
      ) : (
        <div className="aditi-ai-empty">
          <strong>NO ACTIVE AI DECISION</strong>
          <p>
            Enable one or more sensors and start the simulation
            to generate processing results.
          </p>
        </div>
      )}
    </section>
  )
}
